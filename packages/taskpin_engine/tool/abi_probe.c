/*
 * abi_probe.c — print the authoritative sizeof/offsetof of every struct in
 * taskpin_engine.h, as JSON, compiled with the SAME toolchain the Dart tests
 * load the DLL from.
 *
 * Why this exists
 * ---------------
 * dart:ffi has sizeOf<T>() but NO offsetOf. test/abi_layout_test.dart therefore
 * hard-codes the expected numbers and checks them two ways:
 *   - sizeOf<T>()                       (compile-time, exact)
 *   - a runtime sentinel byte-probe     (writes a marker, scans for it)
 *
 * The numbers it hard-codes must come from somewhere trustworthy. That is this
 * program. It is NOT part of the shipped app and NOT part of the engine's
 * public ABI; it just includes the header and reports what the C compiler did.
 *
 * Regenerate with:
 *   bash packages/taskpin_engine/tool/abi_probe.sh
 * which writes packages/taskpin_engine/test/fixtures/abi_layout.json.
 *
 * If this probe ever disagrees with a number in abi_layout_test.dart, the probe
 * is right and the test's constant is stale.
 *
 * Uses offsetof() from <stddef.h>, i.e. the C standard's own answer, so there is
 * no hand arithmetic anywhere in the chain.
 */

#include <stddef.h>
#include <stdio.h>

#include "taskpin_engine.h"

/* The engine is built with MSVC (the Flutter Windows runner's toolchain), so
 * the alignment operator has to be spelled the MSVC way there. _Alignof is
 * C11; the project is C99. */
#if defined(_MSC_VER)
#define TP_ALIGNOF(t) ((unsigned long long)__alignof(t))
#else
#define TP_ALIGNOF(t) (TP_ALIGNOF(t))
#endif

/* Emit one field. `comma` handles the trailing separator. */
#define FIELD(type, member, comma) \
    printf("      { \"name\": \"%s\", \"offset\": %llu }%s\n", #member, \
           (unsigned long long)offsetof(type, member), (comma) ? "," : "")

int main(void) {
    printf("{\n");
    printf("  \"_note\": \"Generated by tool/abi_probe.c against native/engine/taskpin_engine.h. "
           "Do not hand-edit; regenerate with tool/abi_probe.sh.\",\n");
    printf("  \"_arch\": \"x64\",\n");

    /* ── TPSpan ── */
    printf("  \"TPSpan\": {\n");
    printf("    \"size\": %llu,\n", (unsigned long long)sizeof(TPSpan));
    printf("    \"align\": %llu,\n", TP_ALIGNOF(TPSpan));
    printf("    \"fields\": [\n");
    FIELD(TPSpan, text, 1);
    FIELD(TPSpan, color, 1);
    FIELD(TPSpan, font_size, 1);
    FIELD(TPSpan, align, 1);
    FIELD(TPSpan, newline, 1);
    FIELD(TPSpan, is_image, 1);
    FIELD(TPSpan, img_w, 1);
    FIELD(TPSpan, img_h, 0);
    printf("    ]\n");
    printf("  },\n");

    /* ── TPDisplayContent ── */
    printf("  \"TPDisplayContent\": {\n");
    printf("    \"size\": %llu,\n", (unsigned long long)sizeof(TPDisplayContent));
    printf("    \"align\": %llu,\n", TP_ALIGNOF(TPDisplayContent));
    printf("    \"fields\": [\n");
    FIELD(TPDisplayContent, spans, 1);
    FIELD(TPDisplayContent, count, 0);
    printf("    ]\n");
    printf("  },\n");

    /* ── TPDialogItem ── */
    printf("  \"TPDialogItem\": {\n");
    printf("    \"size\": %llu,\n", (unsigned long long)sizeof(TPDialogItem));
    printf("    \"align\": %llu,\n", TP_ALIGNOF(TPDialogItem));
    printf("    \"fields\": [\n");
    FIELD(TPDialogItem, type, 1);
    FIELD(TPDialogItem, value, 1);
    FIELD(TPDialogItem, color, 1);
    FIELD(TPDialogItem, font_size, 1);
    FIELD(TPDialogItem, bold, 1);
    FIELD(TPDialogItem, image, 1);
    FIELD(TPDialogItem, image_width, 1);
    FIELD(TPDialogItem, image_height, 1);
    FIELD(TPDialogItem, url, 1);
    FIELD(TPDialogItem, cmd, 1);
    FIELD(TPDialogItem, bg, 1);
    FIELD(TPDialogItem, web_w, 1);
    FIELD(TPDialogItem, web_h, 1);
    FIELD(TPDialogItem, col_count, 1);
    FIELD(TPDialogItem, row_count, 1);
    FIELD(TPDialogItem, columns, 1);
    FIELD(TPDialogItem, cells, 1);
    FIELD(TPDialogItem, row_urls, 1);
    FIELD(TPDialogItem, row_cmds, 0);
    printf("    ]\n");
    printf("  },\n");

    /* ── TPDialogSpec ── */
    printf("  \"TPDialogSpec\": {\n");
    printf("    \"size\": %llu,\n", (unsigned long long)sizeof(TPDialogSpec));
    printf("    \"align\": %llu,\n", TP_ALIGNOF(TPDialogSpec));
    printf("    \"fields\": [\n");
    FIELD(TPDialogSpec, title, 1);
    FIELD(TPDialogSpec, width, 1);
    FIELD(TPDialogSpec, height, 1);
    FIELD(TPDialogSpec, refresh, 1);
    FIELD(TPDialogSpec, borderless, 1);
    FIELD(TPDialogSpec, clickthrough, 1);
    FIELD(TPDialogSpec, opacity, 1);
    FIELD(TPDialogSpec, bg_color, 1);
    FIELD(TPDialogSpec, transparent_bg, 1);
    FIELD(TPDialogSpec, item_count, 1);
    FIELD(TPDialogSpec, items, 0);
    printf("    ]\n");
    printf("  },\n");

    /* ── TPScriptResult ── */
    printf("  \"TPScriptResult\": {\n");
    printf("    \"size\": %llu,\n", (unsigned long long)sizeof(TPScriptResult));
    printf("    \"align\": %llu,\n", TP_ALIGNOF(TPScriptResult));
    printf("    \"fields\": [\n");
    FIELD(TPScriptResult, rich, 1);
    FIELD(TPScriptResult, display, 1);
    FIELD(TPScriptResult, clickable, 1);
    FIELD(TPScriptResult, click_action, 1);
    FIELD(TPScriptResult, click_url, 1);
    FIELD(TPScriptResult, dialog, 1);
    FIELD(TPScriptResult, error, 1);
    FIELD(TPScriptResult, ok, 0);
    printf("    ]\n");
    printf("  },\n");

    /* ── TPParamDecl ── */
    printf("  \"TPParamDecl\": {\n");
    printf("    \"size\": %llu,\n", (unsigned long long)sizeof(TPParamDecl));
    printf("    \"align\": %llu,\n", TP_ALIGNOF(TPParamDecl));
    printf("    \"fields\": [\n");
    FIELD(TPParamDecl, key, 1);
    FIELD(TPParamDecl, type, 1);
    FIELD(TPParamDecl, label, 0);
    printf("    ]\n");
    printf("  },\n");

    /* ── capacities, so the Dart side can assert its @Array() sizes ── */
    printf("  \"capacities\": {\n");
    printf("    \"TP_MAX_SPANS\": %d,\n", TP_MAX_SPANS);
    printf("    \"TP_SPAN_TEXT_LEN\": %d,\n", TP_SPAN_TEXT_LEN);
    printf("    \"TP_COLOR_LEN\": %d,\n", TP_COLOR_LEN);
    printf("    \"TP_DISPLAY_LEN\": %d,\n", TP_DISPLAY_LEN);
    printf("    \"TP_URL_LEN\": %d,\n", TP_URL_LEN);
    printf("    \"TP_ERROR_LEN\": %d,\n", TP_ERROR_LEN);
    printf("    \"TP_DIALOG_MAX_ITEMS\": %d,\n", TP_DIALOG_MAX_ITEMS);
    printf("    \"TP_DIALOG_MAX_COLS\": %d,\n", TP_DIALOG_MAX_COLS);
    printf("    \"TP_DIALOG_MAX_ROWS\": %d,\n", TP_DIALOG_MAX_ROWS);
    printf("    \"sizeof_int\": %llu,\n", (unsigned long long)sizeof(int));
    printf("    \"sizeof_char\": %llu\n", (unsigned long long)sizeof(char));
    printf("  }\n");

    printf("}\n");
    return 0;
}
