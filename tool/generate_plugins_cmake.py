#!/usr/bin/env python3
"""Generate `windows/generated_plugins_local.cmake` with REAL plugin paths.

WHY THIS EXISTS
---------------
`flutter build windows` writes `windows/flutter/generated_plugins.cmake`, whose
every entry is:

    add_subdirectory(flutter/ephemeral/.plugin_symlinks/<plugin>/windows ...)

That `.plugin_symlinks/` tree is created by Flutter as symlinks. On this machine
those symlinks are created "successfully" but are NOT traversable — CMake then
fails with:

    CMake Error: add_subdirectory given source
      "flutter/ephemeral/.plugin_symlinks/desktop_multi_window/windows"
      which is not an existing directory.

The target path stored in the link is correct (`C:\\Users\\...`), and
`fsutil behavior query SymlinkEvaluation` reports local-to-local links enabled,
so this is not a policy block. It reproduces with the sandbox off and on both
C: and D:, and `mklink /J` junctions fail the same way ("The path cannot be
traversed because it contains an untrustable mount point"). The behaviour is
consistent with Dart's `Link.createSync` writing a reparse point that Windows
will not follow as a directory.

Flutter has no flag to skip the symlink step, and it regenerates its own
`generated_plugins.cmake` on every build, so patching that file does not stick.

WHAT THIS DOES
--------------
Reads `.flutter-plugins-dependencies` (Flutter's own plugin manifest, which
carries absolute paths) and emits an equivalent CMake file that points straight
at the pub-cache directories — no symlinks involved. `windows/CMakeLists.txt`
includes this file in preference to Flutter's.

Re-run it after any `flutter pub get` that changes the plugin set. The
`tool/build_windows.py` wrapper sequences pub-get → this → build.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PLUGIN_MANIFEST = REPO_ROOT / ".flutter-plugins-dependencies"
OUTPUT = REPO_ROOT / "windows" / "generated_plugins_local.cmake"

HEADER = """\
#
# GENERATED by tool/generate_plugins_cmake.py -- do not edit by hand.
#
# Why this file exists instead of using flutter/generated_plugins.cmake:
# see the docstring of tool/generate_plugins_cmake.py. Short version: Flutter's
# .plugin_symlinks tree is not traversable on this machine, so this file points
# CMake at the real pub-cache directories instead.
#
"""


def main() -> int:
    if not PLUGIN_MANIFEST.exists():
        print(f"error: {PLUGIN_MANIFEST} not found; run `flutter pub get` first",
              file=sys.stderr)
        return 1

    data = json.loads(PLUGIN_MANIFEST.read_text(encoding="utf-8"))
    windows_plugins = data.get("plugins", {}).get("windows", [])

    lines: list[str] = [HEADER]
    lines.append("list(APPEND FLUTTER_PLUGIN_LIST")
    for plugin in windows_plugins:
        lines.append(f"  {plugin['name']}")
    lines.append(")")
    lines.append("")
    # jni is an FFI plugin on other platforms, but on Windows it ships a real
    # CMake project, so it is handled through the same path below rather than
    # the FFI list. Keep the variable defined for compatibility.
    lines.append("list(APPEND FLUTTER_FFI_PLUGIN_LIST")
    lines.append(")")
    lines.append("")
    lines.append("set(PLUGIN_BUNDLED_LIBRARIES)")
    lines.append("")

    for plugin in windows_plugins:
        name = plugin["name"]
        raw_path = plugin["path"]
        # The manifest uses Windows separators with a trailing slash. CMake
        # accepts forward slashes on every platform, so normalise to those —
        # collapsing the doubled separators a naive replace would leave behind
        # (`C:\\Users\\` -> `C:/Users/`).
        source = raw_path.replace("\\", "/").rstrip("/")
        while "//" in source[2:]:
            source = source[:2] + source[2:].replace("//", "/")

        var = f"TP_PLUGIN_{name.upper()}_DIR"
        lines.append(f"# {name}")
        lines.append(f'set({var} "{source}")')
        lines.append(f'if(NOT EXISTS "${{{var}}}/windows/CMakeLists.txt")')
        # Two ordinary cases land here, both harmless:
        #   * a plugin with a pure-Dart implementation for Windows
        #     (path_provider_windows ships no windows/ directory at all);
        #   * an FFI plugin whose windows/ project only configures code
        #     generation and defines no `<name>_plugin` target (jni).
        # Flutter's own generated file handles these by listing only the
        # plugins that do define a target, so mirror that: include the
        # directory when it exists, but only wire up a target we know about.
        lines.append(
            f'  message(STATUS "plugin {name}: no windows/CMakeLists.txt, '
            f'no native build")'
        )
        lines.append("else()")
        lines.append(f'  add_subdirectory("${{{var}}}/windows" plugins/{name})')
        # The `<name>_plugin` target is a Flutter convention that not every
        # plugin follows; guard on the target actually existing rather than
        # assuming it, or CMake fails at generate time with
        # "No target \"<name>_plugin\"".
        lines.append(f"  if(TARGET {name}_plugin)")
        lines.append(
            f"    target_link_libraries(${{BINARY_NAME}} PRIVATE {name}_plugin)"
        )
        lines.append(
            f"    list(APPEND PLUGIN_BUNDLED_LIBRARIES $<TARGET_FILE:{name}_plugin>)"
        )
        lines.append(f"    list(APPEND PLUGIN_BUNDLED_LIBRARIES ${{{name}_bundled_libraries}})")
        lines.append("  endif()")
        lines.append("endif()")
        lines.append("")

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(windows_plugins)} plugin(s))")
    for plugin in windows_plugins:
        print(f"  {plugin['name']:26} {plugin['path']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
