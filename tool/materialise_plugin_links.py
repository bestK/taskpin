#!/usr/bin/env python3
"""Materialise Flutter's Windows plugin links as real directory copies.

WHY THIS EXISTS
---------------
`flutter build windows` creates `windows/flutter/ephemeral/.plugin_symlinks/`
as a tree of symlinks (one per plugin, pointing into the pub cache), and
`windows/flutter/generated_plugins.cmake` then does
`add_subdirectory(.../.plugin_symlinks/<plugin>/windows)`.

On this machine every reparse point — symlink AND junction — is created
successfully but cannot then be traversed:

    > mklink /J link target
    Junction created for link <<===>> target
    > dir link
    The path cannot be traversed because it contains an untrusted mount point.

`fsutil behavior query SymlinkEvaluation` reports local-to-local links as
enabled, and it reproduces with the sandbox disabled and on both C: and D:, so
the block is coming from a system-level security product (this box runs both
火绒 and 腾讯电脑管家, either of which is known to intercept reparse points).
Flutter's symlink step fails SILENTLY — it reports success, leaves an empty
`.plugin_symlinks/`, and the failure only surfaces later as a CMake error:

    CMake Error: add_subdirectory given source
      "flutter/ephemeral/.plugin_symlinks/desktop_multi_window/windows"
      which is not an existing directory.

So this script does the same job with a plain recursive copy, which needs no
special privilege and no reparse point.

WHAT IT DOES
------------
For each plugin listed in `windows/flutter/generated_plugins.cmake`, copies the
plugin package from the pub cache into `.plugin_symlinks/<name>/`. CMake then
finds a real directory and the build proceeds.

Run it after `flutter pub get` and before `flutter build windows`. `flutter
build` may re-create the symlinks on each run; if it does, re-run this script.
See `tool/build_windows.py` for the wrapper that sequences the two.

NOTE: `.plugin_symlinks/` is build output and must stay out of git. It is
already covered by the Flutter-generated `windows/flutter/ephemeral/.gitignore`.
"""

from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
GENERATED_PLUGINS = REPO_ROOT / "windows" / "flutter" / "generated_plugins.cmake"
PACKAGE_CONFIG = REPO_ROOT / ".dart_tool" / "package_config.json"
SYMLINK_DIR = REPO_ROOT / "windows" / "flutter" / "ephemeral" / ".plugin_symlinks"


def parse_plugin_lists(cmake_text: str) -> list[str]:
    """Plugin names from the two `list(APPEND ...)` blocks.

    `generated_plugins.cmake` is generated by Flutter and its shape is stable,
    but parsing rather than hard-coding means a plugin added to pubspec.yaml is
    picked up without editing this script.
    """
    names: list[str] = []
    for var in ("FLUTTER_PLUGIN_LIST", "FLUTTER_FFI_PLUGIN_LIST"):
        block = re.search(
            rf"list\(APPEND {var}\s*(.*?)\)",
            cmake_text,
            re.DOTALL,
        )
        if block:
            names.extend(block.group(1).split())
    return names


def package_roots() -> dict[str, Path]:
    """Map package name -> source directory, from pub's package_config.json."""
    data = json.loads(PACKAGE_CONFIG.read_text(encoding="utf-8"))
    roots: dict[str, Path] = {}
    for pkg in data.get("packages", []):
        uri = pkg.get("rootUri", "")
        if not uri.startswith("file:///"):
            continue
        # file:///C:/... -> C:/...
        path = uri[len("file:///"):]
        roots[pkg["name"]] = Path(path.replace("/", "\\") if ":" in path[:3] else path)
    return roots


def main() -> int:
    if not GENERATED_PLUGINS.exists():
        print(f"error: {GENERATED_PLUGINS} not found", file=sys.stderr)
        print("       run `flutter pub get` first", file=sys.stderr)
        return 1
    if not PACKAGE_CONFIG.exists():
        print(f"error: {PACKAGE_CONFIG} not found", file=sys.stderr)
        print("       run `flutter pub get` first", file=sys.stderr)
        return 1

    plugins = parse_plugin_lists(GENERATED_PLUGINS.read_text(encoding="utf-8"))
    if not plugins:
        print("no plugins declared; nothing to do")
        return 0

    roots = package_roots()
    SYMLINK_DIR.mkdir(parents=True, exist_ok=True)

    failures = 0
    for name in plugins:
        source = roots.get(name)
        if source is None:
            print(f"  !! {name}: not in package_config.json", file=sys.stderr)
            failures += 1
            continue
        if not source.is_dir():
            print(f"  !! {name}: source missing at {source}", file=sys.stderr)
            failures += 1
            continue

        # A plugin that does not support Windows is normal (e.g. a pure-Dart
        # FFI helper); generated_plugins.cmake only lists Windows-capable ones,
        # but guard anyway so a stale entry does not abort the build.
        if not (source / "windows").is_dir():
            print(f"  -- {name}: no windows/ platform dir, skipped")
            continue

        target = SYMLINK_DIR / name
        # Remove whatever is there. `shutil.rmtree` cannot delete a symlink or
        # an untraversable junction, so try unlink first.
        if target.is_symlink() or target.exists():
            try:
                target.unlink()
            except OSError:
                try:
                    shutil.rmtree(target)
                except OSError:
                    # A junction created by Flutter: `rmdir` (not `del`) removes
                    # the link itself without touching the target.
                    import subprocess

                    subprocess.run(
                        ["cmd", "/c", "rmdir", str(target)],
                        check=False,
                        capture_output=True,
                    )
        if target.exists() and not target.is_symlink():
            try:
                shutil.rmtree(target)
            except OSError as exc:
                print(f"  !! {name}: could not clear {target}: {exc}", file=sys.stderr)
                failures += 1
                continue

        shutil.copytree(source, target, symlinks=False, dirs_exist_ok=False)
        print(f"  ok {name} -> {target}")

    if failures:
        print(f"\n{failures} plugin(s) failed", file=sys.stderr)
        return 1

    print(f"\nmaterialised {len(plugins)} plugin dir(s) as real copies")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
